import AppKit

/// One piece of copied text.
struct Clip: Codable, Identifiable, Equatable {
    var id = UUID()
    let text: String
    var sourceApp: String?
    var copiedAt: Date
    var pinned = false
}

/// Watches the general pasteboard and keeps the most recent text clips on disk.
final class HistoryStore: ObservableObject {
    /// Newest first. Pinned clips never age out.
    @Published private(set) var clips: [Clip] = []
    /// While set, Copiest records nothing.
    @Published private(set) var pause: Pause?

    static let limit = 500
    /// Skip giant copies, such as a whole log file, so the history file stays small and
    /// search and the secret filter stay fast.
    static let maxBytes = 100_000

    /// Markers that password managers and other apps set on clips that shouldn't be kept.
    /// See http://nspasteboard.org.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    private let prefs: Preferences
    private let pasteboard = NSPasteboard.general
    private var changeCount: Int
    private var timer: Timer?
    private let fileURL: URL
    private let saveQueue = DispatchQueue(label: "com.craftatom.copiest.save", qos: .utility)
    private var pendingSave: DispatchWorkItem?
    /// Every app that was frontmost since the last poll, oldest first. A copy made just
    /// before you switch apps belongs to one of them.
    private var recentApps: [NSRunningApplication] = []

    init(prefs: Preferences) {
        self.prefs = prefs
        let fm = FileManager.default
        let dir = fm.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Copiest", isDirectory: true)
        // Only you can open the folder, so other accounts on this Mac can't read the history.
        try? fm.createDirectory(at: dir, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try? fm.setAttributes([.posixPermissions: 0o700], ofItemAtPath: dir.path)
        fileURL = dir.appendingPathComponent("history.json")
        if let data = try? Data(contentsOf: fileURL) {
            if let saved = try? JSONDecoder().decode([Clip].self, from: data) {
                clips = saved
            } else {
                // Keep an unreadable file, so the next save doesn't destroy pinned clips.
                let backup = dir.appendingPathComponent("history-unreadable-\(Int(Date().timeIntervalSince1970)).json")
                try? fm.moveItem(at: fileURL, to: backup)
            }
        }
        changeCount = pasteboard.changeCount
        recentApps = NSWorkspace.shared.frontmostApplication.map { [$0] } ?? []
        NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] note in
            if let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication {
                self?.recentApps.append(app)
            }
        }
        // The pasteboard has no change notification, so poll its counter. The common run
        // loop mode keeps polling while a menu is open.
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        // Handle a pending copy under the pause state it was made in, then expire the pause.
        if pasteboard.changeCount != changeCount {
            changeCount = pasteboard.changeCount
            record()
        }
        if case .until(let end) = pause, end <= Date() { pause = nil }
        recentApps = NSWorkspace.shared.frontmostApplication.map { [$0] } ?? []
    }

    private func record() {
        if let pause {
            if pause == .nextCopy { self.pause = nil }
            return
        }
        if recentApps.contains(where: { prefs.ignoredApps.contains($0.bundleIdentifier ?? "") }) { return }
        if let types = pasteboard.types, !Self.ignoredTypes.isDisjoint(with: types) { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= Self.maxBytes,
              !(prefs.detectSecrets && SecretFilter.looksSecret(text))
        else { return }
        // People usually copy and then switch apps, so credit the app that was frontmost first.
        add(text, source: recentApps.first?.localizedName)
    }

    /// Pauses recording until the time that the settings choose, or resumes it.
    func togglePause() {
        // A copy made before the toggle follows the old state, not the new one.
        poll()
        pause = pause == nil ? prefs.pauseEnd.pause : nil
    }

    /// Adds a clip at the top, or moves an identical one there.
    private func add(_ text: String, source: String?) {
        if let i = clips.firstIndex(where: { $0.text == text }) {
            var clip = clips.remove(at: i)
            clip.copiedAt = Date()
            clip.sourceApp = source ?? clip.sourceApp
            clips.insert(clip, at: 0)
        } else {
            clips.insert(Clip(text: text, sourceApp: source, copiedAt: Date()), at: 0)
        }
        while clips.filter({ !$0.pinned }).count > Self.limit, let last = clips.lastIndex(where: { !$0.pinned }) {
            clips.remove(at: last)
        }
        save()
    }

    /// Puts a clip back on the clipboard and moves it to the top of the history.
    func copy(_ clip: Clip) {
        pasteboard.clearContents()
        pasteboard.setString(clip.text, forType: .string)
        changeCount = pasteboard.changeCount
        add(clip.text, source: clip.sourceApp)
    }

    func togglePin(_ ids: Set<UUID>) {
        // Pin all when any is unpinned, so a mixed selection behaves predictably.
        let pin = clips.contains { ids.contains($0.id) && !$0.pinned }
        for i in clips.indices where ids.contains(clips[i].id) { clips[i].pinned = pin }
        save()
    }

    func delete(_ ids: Set<UUID>) {
        clips.removeAll { ids.contains($0.id) }
        save()
    }

    /// Removes every clip except pinned ones.
    func clearUnpinned() {
        clips.removeAll { !$0.pinned }
        save()
    }

    /// Writes the history on a background queue. Changes that arrive close together
    /// share one write.
    private func save() {
        pendingSave?.cancel()
        let item = DispatchWorkItem { [clips, fileURL] in Self.write(clips, to: fileURL) }
        pendingSave = item
        saveQueue.asyncAfter(deadline: .now() + 0.5, execute: item)
    }

    /// Writes any pending change before the app quits.
    func flush() {
        guard let pendingSave, !pendingSave.isCancelled else { return }
        pendingSave.cancel()
        saveQueue.sync { Self.write(clips, to: fileURL) }
    }

    private static func write(_ clips: [Clip], to url: URL) {
        guard let data = try? JSONEncoder().encode(clips) else { return }
        try? data.write(to: url, options: [.atomic, .completeFileProtection])
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}
